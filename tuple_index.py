#To treat "TUPLE" as only a "TUPLE" and not as a string we use comma(,) at the last inside paranthesis()

tuple = ("hello",)
print(tuple)
print(type(tuple))

'''"TUPLE" indexing is same as normal indexing method'''

tuple = (9,1,1,0,6,8,6,2,7,4)
print(tuple[1:7])
print(tuple[:10])
print(tuple[0:])


